    cmd.show('sticks',f'{o} and chain A and resi {resis} and not name N+C+O')
    cmd.color(col,f'{o} and chain A and elem C'); cmd.util.cnc(f'{o} and chain A')
    cmd.set_view(view); cmd.ray(2000,1500); cmd.png(out,dpi=300)
